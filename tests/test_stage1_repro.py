"""Stage 1 reproduction test (Step 1b).

The canonical episode table is ``docs/episodes.csv``, regenerated by
``scripts/adni_stage1_build.py``. The provided table is kept as the frozen v1 reference
``docs/episodes_v1_reference.csv``.

This test asserts three things:

a) the *modelling* columns (RID, ORIGPROT, COLPROT, dx_date, DIAGNOSIS, y, m_mri, m_fdg, m_amy,
   m_tau, pattern, n_mod) are IDENTICAL to the v1 reference, row for row;
b) running the script twice produces a **byte-identical** ``episodes.csv`` (determinism);
c) for every modality, ``m_k == 0`` implies the scan date and gap are NaN, ``m_k == 1`` implies
   ``|gap| <= 180``, and the ``{k}_dropped_lowfeat`` counts match the diagnosed numbers.

VISCODE2 is deliberately *not* asserted against the reference: the v1 reference resolves a small
number of ``(RID, EXAMDATE)`` ties in ``DXSUM.csv`` (records sharing an identical ``update_stamp``)
differently from the deterministic rule now used here. VISCODE2 is visit-label metadata that no
downstream model, split or metric reads. ``test_viscode2_differs_only_in_tied_groups`` pins the
number and membership of those differences so they are reported, not hidden.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[1]
REFERENCE = PROJECT_ROOT / "docs" / "episodes_v1_reference.csv"
CANONICAL = PROJECT_ROOT / "docs" / "episodes.csv"
GENERATED = PROJECT_ROOT / "results" / "step01" / "stage1" / "episodes.csv"
SCRIPT = PROJECT_ROOT / "scripts" / "adni_stage1_build.py"
RAW = PROJECT_ROOT / "data" / "raw"

MODS = ["mri", "fdg", "amy", "tau"]
WINDOW = 180

# The columns that any model / split / metric may read. These must match v1 exactly.
MODELLING_COLUMNS = [
    "RID", "ORIGPROT", "COLPROT", "dx_date", "DIAGNOSIS", "y",
    "m_mri", "m_fdg", "m_amy", "m_tau", "pattern", "n_mod",
]

# The exact (RID, dx_date) cells whose VISCODE2 the v1 reference resolves differently, because the
# tied ``update_stamp`` records cannot be reproduced by any deterministic rule (see module docstring
# and results/step01/REPORT.md). Pinned, not ignored.
KNOWN_VISCODE2_DIFFS = {
    (802, "2014-04-04"),
    (4536, "2020-03-03"),
    (6503, "2022-09-14"),
    (10738, "2025-06-04"),
}

# Diagnosed counts of scans found within the window but dropped by the >50%-missing-feature rule.
EXPECTED_DROPPED_LOWFEAT = {"mri": 7, "fdg": 4, "amy": 429, "tau": 86}


def _read(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, dtype=str)


@pytest.fixture(scope="module")
def ref() -> pd.DataFrame:
    assert REFERENCE.is_file(), f"missing v1 reference {REFERENCE}"
    return _read(REFERENCE)


@pytest.fixture(scope="module")
def gen() -> pd.DataFrame:
    assert GENERATED.is_file(), f"missing {GENERATED} — run scripts/adni_stage1_build.py first"
    return _read(GENERATED)


def test_canonical_matches_stage1_output() -> None:
    """docs/episodes.csv is the canonical copy of the Stage 1 output."""
    assert CANONICAL.is_file(), f"missing canonical {CANONICAL}"
    assert CANONICAL.read_bytes() == GENERATED.read_bytes(), (
        "docs/episodes.csv is not byte-identical to results/step01/stage1/episodes.csv"
    )


def test_same_rows_and_superset_of_columns(ref: pd.DataFrame, gen: pd.DataFrame) -> None:
    assert ref.shape[0] == gen.shape[0], f"row count {ref.shape[0]} vs {gen.shape[0]}"
    missing = [c for c in ref.columns if c not in gen.columns]
    assert not missing, f"regenerated table lost reference columns: {missing}"


def test_modelling_columns_identical(ref: pd.DataFrame, gen: pd.DataFrame) -> None:
    """(a) Every modelling column must match the v1 reference exactly, row for row."""
    a = ref[MODELLING_COLUMNS].fillna("__NAN__").reset_index(drop=True)
    b = gen[MODELLING_COLUMNS].fillna("__NAN__").reset_index(drop=True)
    diff = a != b
    if diff.to_numpy().any():
        bad_rows = diff.any(axis=1)
        detail = a[bad_rows].compare(b[bad_rows]).head(20)
        pytest.fail(f"{int(bad_rows.sum())} rows differ in modelling columns:\n{detail}")
    pd.testing.assert_frame_equal(a, b)


def test_viscode2_differs_only_in_tied_groups(ref: pd.DataFrame, gen: pd.DataFrame) -> None:
    """VISCODE2 is metadata; its differences are pinned to the diagnosed tied groups."""
    key = list(zip(ref["RID"].astype(int), ref["dx_date"]))
    a = ref["VISCODE2"].fillna("__NAN__").reset_index(drop=True)
    b = gen["VISCODE2"].fillna("__NAN__").reset_index(drop=True)
    differing = {key[i] for i in range(len(key)) if a[i] != b[i]}
    assert differing == KNOWN_VISCODE2_DIFFS, (
        f"VISCODE2 discrepancy changed. Expected {sorted(KNOWN_VISCODE2_DIFFS)}, "
        f"got {sorted(differing)}."
    )


def test_modality_gating_and_dropped_lowfeat(gen: pd.DataFrame) -> None:
    """(c) m_k == 0 => no date/gap; m_k == 1 => |gap| <= window; dropped_lowfeat counts match."""
    df = gen.copy()
    for k in MODS:
        m = df[f"m_{k}"].astype(int)
        absent = m == 0
        assert df.loc[absent, f"{k}_date"].isna().all(), f"{k}: m_k==0 must have no scan date"
        assert df.loc[absent, f"{k}_gap_days"].isna().all(), f"{k}: m_k==0 must have no gap"
        present = m == 1
        assert df.loc[present, f"{k}_date"].notna().all(), f"{k}: m_k==1 must have a scan date"
        assert df.loc[present, f"{k}_gap_days"].notna().all(), f"{k}: m_k==1 must have a gap"
        gaps = df.loc[present, f"{k}_gap_days"].astype(float).abs()
        assert (gaps <= WINDOW).all(), f"{k}: |gap| must be <= {WINDOW} for m_k==1"
        assert f"{k}_dropped_lowfeat" in df.columns, f"{k}: missing dropped_lowfeat column"
        assert set(df[f"{k}_dropped_lowfeat"].astype(int).unique()).issubset({0, 1})
        assert int(df[f"{k}_dropped_lowfeat"].astype(int).sum()) == EXPECTED_DROPPED_LOWFEAT[k], (
            f"{k}: dropped_lowfeat = {int(df[f'{k}_dropped_lowfeat'].astype(int).sum())}, "
            f"expected {EXPECTED_DROPPED_LOWFEAT[k]}"
        )


def test_two_runs_are_byte_identical(tmp_path: Path) -> None:
    """(b) Determinism: two independent runs produce a byte-identical episodes.csv."""
    if not RAW.is_dir():
        pytest.skip(f"raw data directory {RAW} not available")
    outs = []
    for name in ("run_a", "run_b"):
        out = tmp_path / name
        subprocess.run(
            [sys.executable, str(SCRIPT), "--uploads", str(RAW), "--out", str(out),
             "--window", str(WINDOW)],
            check=True, cwd=str(PROJECT_ROOT),
            stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
        )
        outs.append(out / "episodes.csv")
    assert outs[0].read_bytes() == outs[1].read_bytes(), (
        "two runs of adni_stage1_build.py produced different episodes.csv bytes"
    )
