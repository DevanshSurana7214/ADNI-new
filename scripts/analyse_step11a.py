#!/usr/bin/env python3
"""Step 11a analysis - script-generated tables (uniform protocol of Step 6b, both checkpoint rules).

Reads:
  results/step09/oof_all.parquet    recipe 1 ("R1"): A0-A4 (the Step 9 main experiment)
  results/step11a/oof_all.parquet   R2 (A0/A1/A4) + the recipe-1 sensitivity settings
  configs/step11a_robustness.yaml   the pre-registered grid (run-set -> loss arm)

Writes under results/step11a/:
  main_table_{primary,secondary}.{csv,md}          PN-BAcc(u)/macro-F1/macro-AUROC with CIs per
                                                   run-set (primary operating point)
  runset_pc_{primary,secondary}.{csv,md}           the A1/A4 run-sets at the secondary rho=P(c) op
  paired_r2_{primary,secondary}.{csv,md}           paired A4-A0 and A4-A1 under R2, Holm over the two
                                                   PN-BAcc comparisons + the H3 verdict under R2
  best_epochs_{primary,secondary}.{csv,md}         best-epoch distribution per run-set; flags median<5
                                                   and any epoch-0 selection
  sensitivity_{primary,secondary}.{csv,md}         paired (setting - recipe 1) per setting on
                                                   PN-BAcc(u)/macro-F1/macro-AUROC
  pn_bacc_vs_macro_f1.png                          one figure: PN-BAcc vs macro-F1, every run-set
  analysis.json                                    machine-readable summary incl. the verdicts and
                                                   whether any conclusion changes

Every table here is generated by this script; nothing is hand-typed.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")  # headless
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import yaml  # noqa: E402

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = PROJECT_ROOT / "scripts"
_spec = importlib.util.spec_from_file_location("analyse_step09", SCRIPTS / "analyse_step09.py")
a9 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(a9)  # type: ignore[union-attr]

from adni.metrics import holm  # noqa: E402

DEFAULT_EPISODES = PROJECT_ROOT / "docs" / "episodes.csv"
DEFAULT_SPLITS = PROJECT_ROOT / "results" / "step03" / "splits.json"
DEFAULT_ROBUSTNESS = PROJECT_ROOT / "configs" / "step11a_robustness.yaml"
S11 = PROJECT_ROOT / "results" / "step11a"
STEP9 = PROJECT_ROOT / "results" / "step09"
OUT = PROJECT_ROOT / "results" / "step11a"
CKPT_RULES = ("primary", "secondary")
PROBA_COLS = ["p_CN", "p_MCI", "p_Dementia"]
PRIMARY_OP = {"A0": "argmax", "A1": "uniform", "A2": "argmax", "A3": "argmax", "A4": "uniform"}
R1_ARMS = ("A0", "A1", "A2", "A3", "A4")
NI_MARGIN = 0.02
ALPHA = 0.05
# run-sets plotted/labelled in this order in the figure
FAMILY_COLOR = {"R1": "#444444", "R2": "#d62728", "sensitivity": "#1f77b4"}


def _fmt(v, nd=4):
    return "-" if v is None or (isinstance(v, float) and not np.isfinite(v)) else f"{v:.{nd}f}"


def _ci(d, nd=4):
    return f"{_fmt(d['point'], nd)} [{_fmt(d['ci_low'], nd)}, {_fmt(d['ci_high'], nd)}]"


def ordered_runsets(reg: dict, sens_order=None) -> list[str]:
    """R1 (A0..A4), then R2 (A0/A1/A4), then the sensitivity settings in the grid's order."""
    r1 = [f"R1_{a}" for a in R1_ARMS if f"R1_{a}" in reg]
    r2 = [n for n in reg if reg[n]["family"] == "R2"]
    sens = [n for n in (sens_order or reg) if reg[n]["family"] == "sensitivity"]
    return r1 + r2 + sens


def build_registry(s11_runsets: list[str], arm_by_runset: dict[str, str]) -> dict[str, dict]:
    """Ordered run-set registry: name -> {source, runset/arm, op, family}.

    Recipe-1 rows come from the Step 9 OOF (A0-A4). Step 11a rows are the R2 runs and the recipe-1
    sensitivity settings; their loss arm is read from the Step 11a OOF itself.
    """
    reg: dict[str, dict] = {}
    for arm in R1_ARMS:
        reg[f"R1_{arm}"] = {"source": "step09", "arm": arm, "op": PRIMARY_OP[arm], "family": "R1"}
    for rs in s11_runsets:
        arm = arm_by_runset[rs]
        family = "R2" if rs.startswith("R2_") else "sensitivity"
        reg[rs] = {"source": "step11a", "runset": rs, "arm": arm, "op": PRIMARY_OP[arm],
                   "family": family}
    return reg


def _frame(src, runset: str, reg: dict, rule: str, op: str) -> pd.DataFrame:
    if reg[runset]["source"] == "step09":
        arm = reg[runset]["arm"]
        d = src[(src["arm"] == arm) & (src["ckpt_rule"] == rule) & (src["operating_point"] == op)]
    else:
        d = src[(src["runset"] == runset) & (src["ckpt_rule"] == rule)
                & (src["operating_point"] == op)]
    return a9.seed_average(d)


def _common(a: pd.DataFrame, b: pd.DataFrame):
    idx = a.index.intersection(b.index)
    return a.loc[idx], b.loc[idx]


def _aug(g: pd.DataFrame) -> np.ndarray:
    return np.column_stack([g[PROBA_COLS].to_numpy(), g["w_uniform"].to_numpy(),
                            g["w_prior"].to_numpy()])


def _paired_row(label: str, metric: str, r: dict) -> dict:
    return {"comparison": label, "metric": metric, "diff": r["diff"], "ci_low": r["ci_low"],
            "ci_high": r["ci_high"], "p": r["p"], "n_valid": r["n_valid"]}


def paired(frame_a, frame_b, ep, label: str, metrics=("pn_bacc_uniform", "macro_f1", "macro_auroc")):
    """Paired subject-cluster bootstrap (2,000) for a - b on *metrics* (same episodes)."""
    ga, gb = _common(frame_a, frame_b)
    y = ep["y"].loc[ga.index].to_numpy()
    groups = ep["RID"].loc[ga.index].to_numpy()
    aug_a, aug_b = _aug(ga), _aug(gb)
    mf = a9.metric_family()
    return [_paired_row(label, m, a9.paired_boot(mf[m], y, aug_a, aug_b, groups)) for m in metrics]


def metric_row(runset: str, reg: dict, cis: dict, op: str | None = None) -> dict:
    return {"run-set": runset, "family": reg[runset]["family"], "arm": reg[runset]["arm"],
            "operating_point": op or reg[runset]["op"], "n": cis["n"],
            "pn_bacc": cis["pn_bacc_uniform"], "macro_f1": cis["macro_f1"],
            "macro_auroc": cis["macro_auroc"], "pn_bacc_prior": cis["pn_bacc_prior"],
            "balanced_accuracy": cis["balanced_accuracy"]}

# --------------------------------------------------------------------------- table writers
def write_metric_table(rows, out: Path, stem: str, title: str, note: str = "") -> pd.DataFrame:
    df = pd.DataFrame([{
        "run_set": r["run-set"], "family": r["family"], "arm": r["arm"],
        "operating_point": r["operating_point"], "n": r["n"],
        "pn_bacc": r["pn_bacc"]["point"], "pn_bacc_lo": r["pn_bacc"]["ci_low"],
        "pn_bacc_hi": r["pn_bacc"]["ci_high"],
        "macro_f1": r["macro_f1"]["point"], "macro_f1_lo": r["macro_f1"]["ci_low"],
        "macro_f1_hi": r["macro_f1"]["ci_high"],
        "macro_auroc": r["macro_auroc"]["point"], "macro_auroc_lo": r["macro_auroc"]["ci_low"],
        "macro_auroc_hi": r["macro_auroc"]["ci_high"],
        "balanced_accuracy": r["balanced_accuracy"]["point"]} for r in rows])
    df.to_csv(out / f"{stem}.csv", index=False)
    L = [f"# {title}", ""]
    if note:
        L += [note, ""]
    L += ["| run-set | family | arm | op | n | PN-BAcc(u) | macro-F1 | macro-AUROC |",
          "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['run-set']} | {r['family']} | {r['arm']} | {r['operating_point']} | "
                 f"{r['n']} | {_ci(r['pn_bacc'])} | {_ci(r['macro_f1'])} | {_ci(r['macro_auroc'])} |")
    (out / f"{stem}.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return df


def _holm_str(v) -> str:
    return "-" if v is None or not np.isfinite(v) else f"{v:.4f}"


def write_paired_r2(rows, carry, verdict, full, out: Path, rule: str) -> pd.DataFrame:
    df = pd.DataFrame(rows)
    df.to_csv(out / f"paired_r2_{rule}.csv", index=False)
    if carry:
        pd.DataFrame(carry).to_csv(out / f"paired_r2_carryover_{rule}.csv", index=False)
    L = [f"# Step 11a - paired comparisons under R2 ({rule} checkpoint rule)", "",
         "Seed-averaged OOF, paired subject-cluster bootstrap (2,000), point [95% CI]. The two "
         "pre-registered PN-BAcc(u) comparisons (A4-A0, A4-A1) carry a Holm adjustment; macro-F1 "
         "is judged by the pre-specified non-inferiority margin 0.02.", "",
         "| comparison | metric | diff | 95% CI | p | holm p |", "|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['comparison']} | {r['metric']} | {_fmt(r['diff'])} | "
                 f"[{_fmt(r['ci_low'])}, {_fmt(r['ci_high'])}] | {_fmt(r['p'])} | "
                 f"{_holm_str(r.get('holm_p'))} |")
    L += ["", f"**H3 verdict under R2 (comparators available at R2: A0, A1)** - wins PN-BAcc(u) on "
          f"both after Holm = {verdict['wins_pn_bacc_holm']}; macro-F1 non-inferior = "
          f"{verdict['macro_f1_non_inferior']} -> **{verdict['verdict']}**.", ""]
    if carry:
        L += ["## Carry-over check with the full Step 9 comparator set", "",
              "The Step 9 H3 rule uses four comparators (A0-A3). Only A0 and A1 are retrained under "
              "R2, so the two missing comparators are carried over from recipe 1 (Step 9 A2/A3) and "
              "shown here for completeness; this mixes recipes and is a diagnostic, not the "
              "pre-registered test.", "",
              "| comparison | metric | diff | 95% CI | p | holm p (4) |", "|---|---|---|---|---|---|"]
        for r in carry:
            L.append(f"| {r['comparison']} | {r['metric']} | {_fmt(r['diff'])} | "
                     f"[{_fmt(r['ci_low'])}, {_fmt(r['ci_high'])}] | {_fmt(r['p'])} | "
                     f"{_holm_str(r.get('holm_p'))} |")
        L += ["", f"Full-rule verdict under R2 (Holm over the four PN-BAcc(u) comparisons) = wins "
              f"{full['wins_pn_bacc_holm']}, non-inferior {full['macro_f1_non_inferior']} -> "
              f"**{full['verdict']}**."]
    (out / f"paired_r2_{rule}.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return df


def best_epochs_table(s9, s11, reg, order, out: Path) -> list[dict]:
    recs: list[dict] = []
    for rule in CKPT_RULES:
        for n in order:
            if reg[n]["source"] == "step09":
                d = s9[(s9["arm"] == reg[n]["arm"]) & (s9["ckpt_rule"] == rule)
                       & (s9["operating_point"] == reg[n]["op"])]
            else:
                d = s11[(s11["runset"] == n) & (s11["ckpt_rule"] == rule)
                        & (s11["operating_point"] == reg[n]["op"])]
            be = d.groupby(["seed", "fold"])["best_epoch"].first().to_numpy().astype(float)
            recs.append({
                "run_set": n, "family": reg[n]["family"], "ckpt_rule": rule, "runs": int(len(be)),
                "median": float(np.median(be)), "mean": float(np.mean(be)),
                "min": int(be.min()), "max": int(be.max()),
                "n_below_5": int((be < 5).sum()), "flag_median_below_5": bool(np.median(be) < 5),
                "n_eq_0": int((be == 0).sum()), "flag_epoch_0": bool((be == 0).any())})
    pd.DataFrame(recs).to_csv(out / "best_epochs.csv", index=False)
    L = ["# Step 11a - best-epoch distribution per run-set and checkpoint rule", "",
         "`best_epoch` is the epoch selected by each rule. A run-set is flagged when its median "
         "best epoch is below 5, or when ANY of its runs selected epoch 0.", "",
         "| run-set | family | rule | runs | median | mean | min | max | #(<5) | flag median<5 | "
         "#(==0) | flag epoch 0 |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in recs:
        L.append(f"| {r['run_set']} | {r['family']} | {r['ckpt_rule']} | {r['runs']} | "
                 f"{r['median']:.1f} | {r['mean']:.2f} | {r['min']} | {r['max']} | {r['n_below_5']} | "
                 f"{'YES' if r['flag_median_below_5'] else 'no'} | {r['n_eq_0']} | "
                 f"{'YES' if r['flag_epoch_0'] else 'no'} |")
    (out / "best_epochs.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return recs


def sensitivity_table(frames, ep, reg, order, out: Path) -> dict:
    result: dict[str, list[dict]] = {}
    for rule in CKPT_RULES:
        rows: list[dict] = []
        for n in order:
            if reg[n]["family"] != "sensitivity":
                continue
            ref = f"R1_{reg[n]['arm']}"
            rows += paired(frames[rule][n], frames[rule][ref], ep, f"{n} - {ref}")
        pd.DataFrame(rows).to_csv(out / f"sensitivity_{rule}.csv", index=False)
        L = [f"# Step 11a - sensitivity paired against recipe 1 ({rule} checkpoint rule)", "",
             "Each sensitivity setting minus its recipe-1 counterpart (Step 9 arm), paired "
             "subject-cluster bootstrap (2,000), point [95% CI]. A CI that excludes 0 marks a "
             "setting that materially changes that metric.", "",
             "| comparison | metric | diff | 95% CI | p |", "|---|---|---|---|---|"]
        for r in rows:
            L.append(f"| {r['comparison']} | {r['metric']} | {_fmt(r['diff'])} | "
                     f"[{_fmt(r['ci_low'])}, {_fmt(r['ci_high'])}] | {_fmt(r['p'])} |")
        sig = [r for r in rows if np.isfinite(r["ci_low"]) and (r["ci_low"] > 0 or r["ci_high"] < 0)]
        L += ["", f"Settings with a CI excluding 0: {len(sig)} of {len(rows)} rows "
              f"({sorted({r['comparison'] for r in sig})})."]
        (out / f"sensitivity_{rule}.md").write_text("\n".join(L) + "\n", encoding="utf-8")
        result[rule] = rows
    return result


def make_figure(frames_cis, reg, order, out: Path) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(14, 6.5))
    for ax, rule in zip(axes, CKPT_RULES):
        for n in order:
            c = frames_cis[rule][n]
            x, y = c["pn_bacc_uniform"]["point"], c["macro_f1"]["point"]
            xerr = [[x - c["pn_bacc_uniform"]["ci_low"]], [c["pn_bacc_uniform"]["ci_high"] - x]]
            yerr = [[y - c["macro_f1"]["ci_low"]], [c["macro_f1"]["ci_high"] - y]]
            col = FAMILY_COLOR[reg[n]["family"]]
            ax.errorbar(x, y, xerr=xerr, yerr=yerr, fmt="o", color=col, ms=6, capsize=2, alpha=0.85)
            ax.annotate(n, (x, y), fontsize=7, xytext=(4, 4), textcoords="offset points")
        ax.set_xlabel("PN-BAcc (rho uniform)")
        ax.set_ylabel("macro-F1")
        ax.set_title(f"{rule} checkpoint rule")
        ax.grid(alpha=0.3)
    handles = [plt.Line2D([], [], marker="o", ls="", color=FAMILY_COLOR[f], label=f)
               for f in ("R1", "R2", "sensitivity")]
    axes[0].legend(handles=handles, fontsize=8, loc="lower right")
    fig.suptitle("Step 11a - PN-BAcc vs macro-F1 for every run-set "
                 "(seed-averaged OOF, 95% subject-cluster-bootstrap CIs)")
    fig.tight_layout()
    fig.savefig(out / "pn_bacc_vs_macro_f1.png", dpi=150)
    plt.close(fig)

# --------------------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser(description="Step 11a analysis (robustness only).")
    ap.add_argument("--episodes", type=Path, default=DEFAULT_EPISODES)
    ap.add_argument("--splits", type=Path, default=DEFAULT_SPLITS)
    ap.add_argument("--robustness", type=Path, default=DEFAULT_ROBUSTNESS)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--bootstrap", type=int, default=2000)
    a = ap.parse_args()
    a9.N_BOOT = a.bootstrap
    a.out.mkdir(parents=True, exist_ok=True)

    ep = pd.read_csv(a.episodes, dtype={"pattern": str}).set_index("episode_id")
    blob = json.loads(Path(a.splits).read_text())
    w = a9.build_weights(ep, blob)

    def _load(path: Path) -> pd.DataFrame:
        d = pd.read_parquet(path).merge(w, on=["seed", "fold", "episode_id"], how="left")
        assert d["w_uniform"].notna().all(), f"missing fold weights for {path}"
        return d

    s9 = _load(STEP9 / "oof_all.parquet")
    s11 = _load(S11 / "oof_all.parquet")
    print(f"[data] step9 rows={len(s9)} step11a rows={len(s11)} "
          f"runsets={s11['runset'].nunique()}", flush=True)

    arm_by_runset = s11.groupby("runset")["arm"].first().to_dict()
    spec = yaml.safe_load(Path(a.robustness).read_text())
    sens_order = [s["name"] for s in spec.get("sensitivity", [])]
    reg = build_registry(list(arm_by_runset), arm_by_runset)
    order = ordered_runsets(reg, sens_order)
    srcs = {"step09": s9, "step11a": s11}

    frames = {r: {} for r in CKPT_RULES}
    cis = {r: {} for r in CKPT_RULES}
    for rule in CKPT_RULES:
        for n in order:
            g = _frame(srcs[reg[n]["source"]], n, reg, rule, reg[n]["op"])
            frames[rule][n] = g
            cis[rule][n] = a9.evaluate(g, ep)
        print(f"[eval {rule}] evaluated {len(order)} run-sets", flush=True)

    for rule in CKPT_RULES:
        rows = [metric_row(n, reg, cis[rule][n]) for n in order]
        write_metric_table(rows, a.out, f"main_table_{rule}",
                           f"Step 11a - metrics per run-set ({rule} checkpoint rule)",
                           note="Seed-averaged OOF, pooled, one 2,000-resample subject-cluster "
                                "bootstrap (Step 6b uniform protocol). point [95% CI]. One row per "
                                "run-set at its primary operating point (A1/A4 -> rho uniform; "
                                "A0/A3 -> argmax). R1_* = recipe 1 = Step 9.")
        print(f"[main {rule}] wrote main_table_{rule}.csv", flush=True)

    for rule in CKPT_RULES:
        rows = []
        for n in order:
            if reg[n]["arm"] not in ("A1", "A4"):
                continue
            g = _frame(srcs[reg[n]["source"]], n, reg, rule, "P(c)")
            rows.append(metric_row(n, reg, a9.evaluate(g, ep), op="P(c)"))
        write_metric_table(rows, a.out, f"runset_pc_{rule}",
                           f"Step 11a - A1/A4 run-sets at rho=P(c) ({rule} checkpoint rule)",
                           note="Secondary operating point (pattern-neutral at natural class "
                                "prevalence). Same protocol as the main table.")
        print(f"[pc {rule}] wrote runset_pc_{rule}.csv", flush=True)

    verdicts: dict[str, dict] = {}
    fulls: dict[str, dict] = {}
    for rule in CKPT_RULES:
        a4 = frames[rule]["R2_A4"]
        rows: list[dict] = []
        for comp in ("R2_A0", "R2_A1"):
            rows += paired(a4, frames[rule][comp], ep, f"A4(R2) - {comp}")
        pn = [r for r in rows if r["metric"] == "pn_bacc_uniform"]
        for r, h in zip(pn, holm([r["p"] for r in pn])):
            r["holm_p"] = float(h)
        for r in rows:
            r.setdefault("holm_p", None)
        f1 = [r for r in rows if r["metric"] == "macro_f1"]
        wins = all(r["diff"] > 0 and np.isfinite(r["holm_p"]) and r["holm_p"] < ALPHA for r in pn)
        ni_ok = all(r["ci_low"] > -NI_MARGIN for r in f1)
        verdict = ("H3 supported under R2 (comparators A0/A1)" if (wins and ni_ok)
                   else "trade-off (A4 wins PN-BAcc but fails macro-F1 non-inferiority)" if wins
                   else "negative result")
        verdicts[rule] = {"wins_pn_bacc_holm": bool(wins), "macro_f1_non_inferior": bool(ni_ok),
                          "verdict": verdict,
                          "pn_bacc_diffs": {r["comparison"]: r["diff"] for r in pn},
                          "pn_bacc_holm_p": {r["comparison"]: r["holm_p"] for r in pn},
                          "macro_f1_ci_low": {r["comparison"]: r["ci_low"] for r in f1}}

        carry: list[dict] = []
        for comp in ("R1_A2", "R1_A3"):
            carry += paired(a4, frames[rule][comp], ep, f"A4(R2) - {comp}")
        # copies, so the 4-comparison Holm values never overwrite the two-comparison ones in `rows`
        pn4 = [dict(r) for r in pn] + [r for r in carry if r["metric"] == "pn_bacc_uniform"]
        for r, h in zip(pn4, holm([r["p"] for r in pn4])):
            r["holm_p"] = float(h)
        for r in carry:
            r.setdefault("holm_p", None)
        f14 = f1 + [r for r in carry if r["metric"] == "macro_f1"]
        wins4 = all(r["diff"] > 0 and np.isfinite(r["holm_p"]) and r["holm_p"] < ALPHA for r in pn4)
        ni4 = all(r["ci_low"] > -NI_MARGIN for r in f14)
        fulls[rule] = {"wins_pn_bacc_holm": bool(wins4), "macro_f1_non_inferior": bool(ni4),
                       "verdict": ("H3 supported under R2 (full four comparators)" if (wins4 and ni4)
                                   else "trade-off" if wins4 else "negative result"),
                       "pn_bacc_holm_p": {r["comparison"]: r["holm_p"] for r in pn4}}
        write_paired_r2(rows, carry, verdicts[rule], fulls[rule], a.out, rule)
        print(f"[paired {rule}] partial: {verdict} | full-rule: {fulls[rule]['verdict']}", flush=True)

    be = best_epochs_table(s9, s11, reg, order, a.out)
    sens = sensitivity_table(frames, ep, reg, order, a.out)
    make_figure(cis, reg, order, a.out)
    print("[figure] wrote pn_bacc_vs_macro_f1.png", flush=True)

    s9v = json.loads((STEP9 / "analysis.json").read_text())["verdicts"]
    conclusions: dict[str, dict] = {}
    for rule in CKPT_RULES:
        r2_supported = bool(verdicts[rule]["wins_pn_bacc_holm"]
                            and verdicts[rule]["macro_f1_non_inferior"])
        conclusions[rule] = {
            "step9_verdict": s9v[rule]["verdict"],
            "r2_verdict_partial_comparators": verdicts[rule]["verdict"],
            "r2_verdict_full_comparators": fulls[rule]["verdict"],
            "primary_conclusion_changes": r2_supported,
            "a4_r2_minus_a1_pn_bacc": verdicts[rule]["pn_bacc_diffs"].get("A4(R2) - R2_A1"),
            "a4_r2_minus_a1_pn_bacc_holm_p": verdicts[rule]["pn_bacc_holm_p"].get("A4(R2) - R2_A1"),
        }

