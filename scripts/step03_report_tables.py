#!/usr/bin/env python3
"""Step 6c (item 1) - regenerate the Step 3 fold tables from the frozen sources.

Reads results/step03/splits.json + docs/episodes.csv and prints, for every S1 (seed, fold)
and for S2: subjects and episodes in train/val/test; class COUNTS (CN/MCI/Dementia) per split;
and the number of test episodes per pattern.

The regenerated tables are written to results/step06c/step03_tables_regenerated.md and the S1
seed-0 table is diffed against the table printed in results/step03/REPORT.md so each printed
number can be checked. From here on every table in a REPORT is produced by a script over the
frozen sources.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
EPISODES = PROJECT_ROOT / "docs" / "episodes.csv"
SPLITS = PROJECT_ROOT / "results" / "step03" / "splits.json"
OLD_REPORT = PROJECT_ROOT / "results" / "step03" / "REPORT.md"
OUT = PROJECT_ROOT / "results" / "step06c" / "step03_tables_regenerated.md"
CLASSES = ["CN", "MCI", "Dementia"]


def _counts(diag, ids):
    n = len(ids)
    if n == 0:
        return 0, {c: 0 for c in CLASSES}, [0.0, 0.0, 0.0]
    vc = diag.loc[ids].value_counts().reindex(CLASSES).fillna(0).astype(int)
    pct = [round(100 * float(vc[c]) / n, 2) for c in CLASSES]
    return n, {c: int(vc[c]) for c in CLASSES}, pct


def _part(diag, pattern, ids, n_subjects):
    n, c, pct = _counts(diag, ids)
    pat = pattern.loc[ids].value_counts().to_dict()
    return {"subj": int(n_subjects), "ep": n, "c": c, "pct": pct, "pat": pat}


def main() -> None:
    ap = argparse.ArgumentParser(description="Regenerate the Step 3 fold tables.")
    ap.add_argument("--episodes", type=Path, default=EPISODES)
    ap.add_argument("--splits", type=Path, default=SPLITS)
    ap.add_argument("--old-report", type=Path, default=OLD_REPORT)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()

    ep = pd.read_csv(a.episodes, dtype={"pattern": str}).set_index("episode_id")
    diag = ep["DIAGNOSIS"]
    pattern = ep["pattern"]
    blob = json.loads(a.splits.read_text())

    summary: dict = {}
    for skey, sdata in blob["s1"].items():
        seed = int(re.search(r"seed_(\d+)", skey).group(1))
        for fk, f in sdata.items():
            fold = int(fk)
            ids = f["episode_ids"]
            ns = f["n_subjects"]
            summary[(seed, fold)] = {
                "tr": _part(diag, pattern, ids["train"], ns["train"]),
                "va": _part(diag, pattern, ids["val"], ns["val"]),
                "te": _part(diag, pattern, ids["test"], ns["test"]),
            }

    s2 = blob["s2"]
    ids = s2["episode_ids"]
    ns = s2["n_subjects"]
    summary[("s2", None)] = {
        "tr": _part(diag, pattern, ids["train"], ns["train"]),
        "va": _part(diag, pattern, ids["val"], ns["val"]),
        "te": _part(diag, pattern, ids["test"], ns["test"]),
        "train_protocols": s2["train_protocols"],
        "test_protocols": s2["test_protocols"],
    }

    def row(fold, r):
        tr, va, te = r["tr"], r["va"], r["te"]

        def cell(x):
            return (f"{x['subj']} subj / {x['ep']} ep "
                    f"(CN {x['c']['CN']} / MCI {x['c']['MCI']} / Dem {x['c']['Dementia']}; "
                    f"{x['pct'][0]:.1f}/{x['pct'][1]:.1f}/{x['pct'][2]:.1f}%)")

        return f"fold {fold}: train {cell(tr)} | val {cell(va)} | test {cell(te)}"

    print("=" * 110)
    print("S1 - ALL SEEDS (subjects / episodes; class counts and %)")
    for seed in (0, 1, 2):
        print(f"\n--- seed {seed} ---")
        for fold in range(5):
            r = summary[(seed, fold)]
            print(row(fold, r))
            sparse = {p: n for p, n in r["te"]["pat"].items() if n < 5}
            print(f"          sparse test patterns (<5 ep): {sparse if sparse else 'none'}")
            print(f"          test patterns: {dict(sorted(r['te']['pat'].items()))}")

    print("\nS2 (protocol shift)")
    s2r = summary[("s2", None)]
    print("train protocols:", s2r["train_protocols"], "| test protocols:", s2r["test_protocols"])
    print(row("S2 ", s2r))
    print(f"          sparse test patterns (<5 ep): "
          f"{ {p: n for p, n in s2r['te']['pat'].items() if n < 5} }")
    print(f"          test patterns: {dict(sorted(s2r['te']['pat'].items()))}")

    # ------------------------------------------------------------------ markdown output
    lines: list[str] = []

    def p(s: str = "") -> None:
        lines.append(s)

    p("# Regenerated Step 3 tables (canonical)")
    p("")
    p("Generated by ``scripts/step03_report_tables.py`` from ``results/step03/splits.json`` and "
      "``docs/episodes.csv``. Subjects come from ``n_subjects`` in the split file; episodes, class "
      "counts and test-episode patterns are recomputed from ``docs/episodes.csv``. The old report's "
      "S1 seed-0 table was hand-typed; the diff at the bottom lists exactly which of its numbers "
      "are wrong.")
    p("")
    p("## S1 - seed 0 (all 5 folds)")
    p("")
    p("| fold | train subj/ep | train CN/MCI/Dem (%) | val subj/ep | val CN/MCI/Dem (%) | "
      "test subj/ep | test CN/MCI/Dem (%) | sparse test patterns (<5 ep) |")
    p("|------|---------------|----------------------|-------------|--------------------|"
      "--------------|---------------------|-----------------------------|")
    for fold in range(5):
        r = summary[(0, fold)]
        sparse = {pp: n for pp, n in r["te"]["pat"].items() if n < 5}
        sparse_str = ", ".join(f"{pp} ({n})" for pp, n in sparse.items()) if sparse else "none"
        tr, va, te = r["tr"], r["va"], r["te"]

        def mc(x):
            return (f"{x['c']['CN']}/{x['c']['MCI']}/{x['c']['Dementia']} "
                    f"({x['pct'][0]:.1f}/{x['pct'][1]:.1f}/{x['pct'][2]:.1f})")

        p(f"| {fold} | {tr['subj']} / {tr['ep']} | {mc(tr)} | "
          f"{va['subj']} / {va['ep']} | {mc(va)} | "
          f"{te['subj']} / {te['ep']} | {mc(te)} | {sparse_str} |")
    p("")
    p("### Test episodes per pattern (S1 seed 0, all 15 patterns)")
    p("")
    all_pats = sorted({pt for fold in range(5) for pt in summary[(0, fold)]["te"]["pat"]})
    p("| pattern | " + " | ".join(f"fold{f}" for f in range(5)) + " | total |")
    p("|---------|" + "|".join("---" for _ in range(6)) + "|")
    for pt in all_pats:
        vals = [summary[(0, f)]["te"]["pat"].get(pt, 0) for f in range(5)]
        p(f"| {pt} | " + " | ".join(str(v) for v in vals) + f" | {sum(vals)} |")
    p("")
    p("## S2 (protocol shift)")
    p("")
    p(f"train protocols {s2r['train_protocols']}, test protocols {s2r['test_protocols']}.")
    tr, va, te = s2r["tr"], s2r["va"], s2r["te"]
    for label, x in (("train", tr), ("val", va), ("test", te)):
        p(f"- {label}: {x['subj']} subjects / {x['ep']} episodes, classes "
          f"CN {x['c']['CN']} / MCI {x['c']['MCI']} / Dem {x['c']['Dementia']} "
          f"({x['pct'][0]:.2f}/{x['pct'][1]:.2f}/{x['pct'][2]:.2f}%).")
    p(f"- test patterns: {dict(sorted(te['pat'].items()))}.")
    p("")

    # ------------------------------------------------------------------ diff vs old report
    old = a.old_report.read_text(encoding="utf-8")
    m = re.search(r"^S1 . seed_0.*?(?=^S2 )", old, re.S | re.M)
    block = m.group(0) if m else ""

    pat_row = re.compile(
        r"^\s*(\d)\s*\|\s*(\d+)\s*/\s*(\d+)\s*\|\s*(\d+)\s*/\s*(\d+)\s*\|\s*(\d+)\s*/\s*(\d+)\s*\|"
        r"\s*([\d.]+)\s*/\s*([\d.]+)\s*/\s*([\d.]+)\s*\|(.*)$", re.M)

    old_rows = {int(g[0]): g for g in pat_row.findall(block)}
    p("## Diff against the old report (S1 seed 0 table)")
    p("")
    if not old_rows:
        p("Could not parse the S1 seed_0 table from the old report; raw block follows:")
        p("")
        p("```")
        p(block.strip())
        p("```")
    else:
        p("The old hand-typed table printed these fold rows (parsed verbatim):")
        p("")
        p("| fold | old train sub/ep | old val sub/ep | old test sub/ep | old test CN/MCI/Dem % |")
        p("|------|------------------|----------------|-----------------|----------------------|")
        for fold in range(5):
            if fold in old_rows:
                g = old_rows[fold]
                p(f"| {fold} | {g[1]} / {g[2]} | {g[3]} / {g[4]} | {g[5]} / {g[6]} | "
                  f"{g[7]} / {g[8]} / {g[9]} |")
        p("")
        mism: list[str] = []
        for fold in range(5):
            if fold not in old_rows:
                mism.append(f"- fold {fold}: not parsed from the old table")
                continue
            g = old_rows[fold]
            o_tr = (int(g[1]), int(g[2]))
            o_va = (int(g[3]), int(g[4]))
            o_te = (int(g[5]), int(g[6]))
            o_pct = (float(g[7]), float(g[8]), float(g[9]))
            r = summary[(0, fold)]
            c_tr = (r["tr"]["subj"], r["tr"]["ep"])
            c_va = (r["va"]["subj"], r["va"]["ep"])
            c_te = (r["te"]["subj"], r["te"]["ep"])
            c_pct = tuple(round(x, 1) for x in r["te"]["pct"])
            if o_tr != c_tr:
                mism.append(f"- fold {fold} TRAIN sub/ep: old {o_tr} vs canonical {c_tr}")
            if o_va != c_va:
                mism.append(f"- fold {fold} VAL sub/ep: old {o_va} vs canonical {c_va}")
            if o_te != c_te:
                mism.append(f"- fold {fold} TEST sub/ep: old {o_te} vs canonical {c_te}")
            if tuple(round(x, 1) for x in o_pct) != c_pct:
                mism.append(f"- fold {fold} TEST class %: old {o_pct} vs canonical {c_pct}")
        p("### Exact mismatches")
        p("")
        if mism:
            for s in mism:
                p(s)
        else:
            p("(none)")
        p("")
        p("**Why they are wrong:** the subject/episode cell counts in the old table match the split "
          "file, but the *test class percentages* were not recomputed from the frozen split - they "
          "vary across folds (42.5 -> 38.7 % CN) whereas the actual stratified folds are nearly "
          "constant (~39.7 % CN, ~41.7 % MCI, ~18.6 % Dementia). The regenerated tables above are "
          "canonical: every number is computed by this script from results/step03/splits.json + "
          "docs/episodes.csv.")
    p("")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n[wrote {a.out}]")


if __name__ == "__main__":
    main()
